-- StarFx
-- Location: ReplicatedStorage.SummonPlaza.Fx.Shared.StarFx (ModuleScript, client only)
--
-- Shooting stars made of: a glowing head (billboard: soft glow + 4-point
-- flare) and a streak behind it: two camera-facing Beams from the head to
-- the tail, a bright core and a wide soft halo, both fading out toward the
-- tail. (Plain beams, no texture: a texture's thin core vanishes when the
-- streak is only a few pixels wide, far up in the sky.) Used by
--   * StarterPlayerScripts.NightSkyClient -- the lobby's random shooting stars
--   * Fx.SummonCutscene                   -- the star-fall summon cutscene
-- Everything is created on this client only (never replicated).
-- Textures: generated by a Python script (fx_gen.py), all white so they
-- can be tinted.

local StarFx = {}

StarFx.Textures = {
	Glow = "rbxassetid://129082353521012",
	Flare = "rbxassetid://118105425284877",
	Sparkle = "rbxassetid://124180622206925",
	Ring = "rbxassetid://138415430859193",
	Rays = "rbxassetid://105713675770887",
	Streak = "rbxassetid://118221467064701",
	BlackHoleDisc = "rbxassetid://80451043326989",
	BlackHoleCore = "rbxassetid://118097810519366",
	Vignette = "rbxassetid://89930927092983", -- screen edges (clear middle)
}

StarFx.DefaultColor = Color3.fromRGB(196, 222, 255) -- the plain blue-white of a normal star

export type Star = {
	part: BasePart,
	head: Attachment,
	tail: Attachment,
	beam: Beam,
	halo: Beam,
	gui: BillboardGui,
	glow: ImageLabel,
	flare: ImageLabel,
	color: Color3,
	headSize: number,
	SetColor: (Star, Color3) -> (),
	Place: (Star, Vector3, Vector3) -> (),
	SetHeadSize: (Star, number) -> (),
	SetWidth: (Star, number, number) -> (),
	SetFade: (Star, number) -> (),
	Destroy: (Star) -> (),
}

local folder: Folder? = nil
function StarFx.Folder(): Folder
	local f = folder
	if f and f.Parent then return f end
	local nf = Instance.new("Folder")
	nf.Name = "LocalStarFx"
	nf.Parent = workspace
	folder = nf
	return nf
end

local function image(parent: Instance, name: string, id: string, z: number): ImageLabel
	local img = Instance.new("ImageLabel")
	img.Name = name
	img.AnchorPoint = Vector2.new(0.5, 0.5)
	img.Position = UDim2.fromScale(0.5, 0.5)
	img.Size = UDim2.fromScale(1, 1)
	img.BackgroundTransparency = 1
	img.Image = id
	img.ZIndex = z
	img.Parent = parent
	return img
end

local Star = {}
Star.__index = Star

-- transparency along the streak (0 = head, 1 = tail), faded by `fade`
local CORE = { { 0, 0 }, { 0.15, 0.1 }, { 0.6, 0.55 }, { 1, 1 } }
local HALO = { { 0, 0.55 }, { 0.4, 0.8 }, { 1, 1 } }
local function streak(points: {{number}}, fade: number): NumberSequence
	local kps = {}
	for _, p in points do
		table.insert(kps, NumberSequenceKeypoint.new(p[1], 1 - (1 - p[2]) * (1 - fade)))
	end
	return NumberSequence.new(kps)
end

function Star.SetColor(self: Star, color: Color3)
	self.color = color
	self.beam.Color = ColorSequence.new(Color3.new(1, 1, 1):Lerp(color, 0.35), color)
	self.halo.Color = ColorSequence.new(color)
	self.glow.ImageColor3 = color
	self.flare.ImageColor3 = Color3.new(1, 1, 1):Lerp(color, 0.55)
end

-- head = where the star is, tail = the end of its streak (world space)
function Star.Place(self: Star, head: Vector3, tail: Vector3)
	self.part.CFrame = CFrame.new(head)
	self.tail.Position = tail - head
end

-- glow size in studs (the flare is drawn 1.6x as wide)
function Star.SetHeadSize(self: Star, studs: number)
	self.headSize = studs
	self.gui.Size = UDim2.fromScale(studs * 1.6, studs * 1.6)
end

-- streak widths in studs at the head and the tail (the halo is 3.5x as wide)
function Star.SetWidth(self: Star, head: number, tail: number)
	self.beam.Width0 = head
	self.beam.Width1 = tail
	self.halo.Width0 = head * 3.5
	self.halo.Width1 = tail * 2
end

-- 0 = fully visible, 1 = gone
function Star.SetFade(self: Star, t: number)
	t = math.clamp(t, 0, 1)
	self.beam.Transparency = streak(CORE, t)
	self.halo.Transparency = streak(HALO, t)
	self.glow.ImageTransparency = t
	self.flare.ImageTransparency = math.clamp(t + 0.1, 0, 1)
end

function Star.Destroy(self: Star)
	self.part:Destroy()
end

-- A new star (head size and streak widths in studs).
function StarFx.New(color: Color3?, headSize: number?, width: number?): Star
	local part = Instance.new("Part")
	part.Name = "Star"
	part.Anchored = true
	part.CanCollide = false
	part.CanQuery = false
	part.CanTouch = false
	part.CastShadow = false
	part.Transparency = 1
	part.Size = Vector3.new(0.2, 0.2, 0.2)
	local head = Instance.new("Attachment")
	head.Name = "Head"
	head.Parent = part
	local tail = Instance.new("Attachment")
	tail.Name = "Tail"
	tail.Parent = part
	local function newBeam(name: string, brightness: number): Beam
		local b = Instance.new("Beam")
		b.Name = name
		b.Attachment0 = head
		b.Attachment1 = tail
		b.FaceCamera = true
		b.LightEmission = 1
		b.LightInfluence = 0
		b.Brightness = brightness
		b.Segments = 1
		b.Parent = part
		return b
	end
	local halo = newBeam("Halo", 2)
	local beam = newBeam("Core", 5)
	local gui = Instance.new("BillboardGui")
	gui.Name = "HeadGlow"
	gui.LightInfluence = 0
	gui.Brightness = 2
	gui.AlwaysOnTop = false
	gui.MaxDistance = 1e5
	gui.ResetOnSpawn = false
	gui.Adornee = part
	gui.Parent = part
	local glow = image(gui, "Glow", StarFx.Textures.Glow, 1)
	glow.Size = UDim2.fromScale(0.62, 0.62)
	local flare = image(gui, "Flare", StarFx.Textures.Flare, 2)
	local self = setmetatable({
		part = part, head = head, tail = tail, beam = beam, halo = halo, gui = gui, glow = glow, flare = flare,
		color = color or StarFx.DefaultColor, headSize = 0,
	}, Star) :: any
	self:SetColor(color or StarFx.DefaultColor)
	self:SetFade(0)
	self:SetHeadSize(headSize or 30)
	local w = width or 8
	self:SetWidth(w, w * 0.25)
	part.Parent = StarFx.Folder()
	return self :: Star
end

-- A flat camera-facing image in the world (rings, black hole...), size in studs.
function StarFx.Billboard(id: string, at: Vector3, studs: number, color: Color3?, parent: Instance?): (BillboardGui, ImageLabel, BasePart)
	local part = Instance.new("Part")
	part.Name = "FxBillboard"
	part.Anchored = true
	part.CanCollide = false
	part.CanQuery = false
	part.CanTouch = false
	part.CastShadow = false
	part.Transparency = 1
	part.Size = Vector3.new(0.2, 0.2, 0.2)
	part.CFrame = CFrame.new(at)
	local gui = Instance.new("BillboardGui")
	gui.LightInfluence = 0
	gui.Brightness = 2
	gui.MaxDistance = 1e5
	gui.Size = UDim2.fromScale(studs, studs)
	gui.Adornee = part
	gui.Parent = part
	local img = image(gui, "Image", id, 1)
	img.ImageColor3 = color or Color3.new(1, 1, 1)
	part.Parent = parent or StarFx.Folder()
	return gui, img, part
end

return StarFx
